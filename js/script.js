let currentPage = 1;
const rowsPerPage = 10;
let map,
  markers = [],
  tableRows = [];
let filteredPlaces = [...places]; // initially same as all places

function initMap() {
  map = new google.maps.Map(document.getElementById("map"), {
    center: { lat: -26, lng: 28 },
    zoom: 9,
  });
  console.log(places);
  renderTable();
}

function renderTable() {
  const tableBody = document.querySelector("#placesTable tbody");
  tableBody.innerHTML = "";

  // clear old markers
  markers.forEach((m) => m.setMap(null));
  markers = [];
  tableRows = [];

  const start = (currentPage - 1) * rowsPerPage;
  const end = start + rowsPerPage;
  const pageItems = filteredPlaces.slice(start, end);

  pageItems.forEach((place, index) => {
    // Add row to table
    const row = document.createElement("tr");
    row.innerHTML = `
          <td>${place.churchName}</td>
          <td>${place.churchAddress}</td>
          <td>${place.pastorFirstLastName}</td>
          `;
    tableBody.appendChild(row);
    tableRows.push(row);

    // Add marker to map
    const marker = new google.maps.Marker({
      position: { lat: place.churchLatitude, lng: place.churchLongitude },
      map: map,
      title: place.churchName,
    });
    markers.push(marker);

    // Row click → highlight marker
    row.addEventListener("click", () => highlight(index));

    // Marker click → highlight row
    marker.addListener("click", () => highlight(index));
  });

  // update page info
  document.getElementById(
    "pageInfo"
  ).textContent = `Page ${currentPage} of ${Math.max(
    1,
    Math.ceil(filteredPlaces.length / rowsPerPage)
  )}`;
}

function highlight(index) {
  // Reset all markers and rows
  markers.forEach((m) => m.setAnimation(null));
  tableRows.forEach((r) => r.classList.remove("highlight"));

  // Highlight chosen marker and row
  markers[index].setAnimation(google.maps.Animation.BOUNCE);
  setTimeout(() => markers[index].setAnimation(null), 1600);
  tableRows[index].classList.add("highlight");

  // Pan map to the marker
  map.panTo(markers[index].getPosition());
  map.setZoom(15);
}

function nextPage() {
  if (currentPage * rowsPerPage < filteredPlaces.length) {
    currentPage++;
    renderTable();
  }
}

function prevPage() {
  if (currentPage > 1) {
    currentPage--;
    renderTable();
  }
}

function applyFilter() {
  const query = document.getElementById("searchBox").value.toLowerCase();
  filteredPlaces = places.filter((p) =>
    p.churchName.toLowerCase().includes(query)
  );
  currentPage = 1; // reset to first page
  renderTable();
}

function displayCurrentYear() {
  currentYear = document.getElementById("currentYear");

  currentYear = getYear();
}

window.onload = initMap;
